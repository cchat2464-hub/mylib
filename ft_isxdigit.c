/* This function checks the hexadecimal numbers
 * 0123456789ABCDEF*/

int ft_isxdigit(char c)
{
	if (( c>='0' && c<='9')||
		(c >='a' && c <='f')||
			(c >='A' && c<='F'))
		return (1);
	else
	 	return (0);
}


